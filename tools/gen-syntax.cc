// Writes syntax/Giac.sublime-syntax: a highlighting grammar for Giac in the
// sublime-syntax format that syntect (jotter, bat) and Sublime Text read.
//
// The list of built-in commands comes from libgiac itself, so the grammar
// matches the Giac it was generated with. Regenerate after a Giac upgrade:
//   cmake --build build --target gen-syntax && build/gen-syntax > syntax/Giac.sublime-syntax

#include <giac/config.h>
#include <giac/giac.h>
#include <giac/input_lexer.h>

#include <cctype>
#include <cstdio>
#include <cstring>
#include <set>
#include <string>

// Words the grammar colours as keywords or constants instead of commands.
static const std::set<std::string> KEYWORDS = {
    "if", "then", "else", "elif", "fi", "for", "from", "to", "by", "step", "do", "od",
    "while", "end", "return", "break", "continue", "local", "global", "function", "ffunction",
    "case", "switch", "default", "try", "catch", "repeat", "until", "in", "and", "or", "not",
    "xor", "mod",
    // French forms (Xcas accepts both)
    "si", "alors", "sinon", "fsi", "pour", "de", "jusque", "pas", "faire", "fpour", "tantque",
    "ftantque", "retourne", "fonction", "ffonction", "repeter", "jusqua", "et", "ou", "non"};
static const std::set<std::string> CONSTANTS = {
    "pi", "i", "e", "infinity", "inf", "undef", "true", "false", "euler_gamma", "vrai", "faux"};

static bool plain_identifier(const char *s)
{
	if (!s || !std::isalpha((unsigned char)s[0]))
		return false;
	for (const char *p = s; *p; ++p)
		if (!std::isalnum((unsigned char)*p) && *p != '_')
			return false;
	return std::strlen(s) > 1;
}

static std::string alternation(const std::set<std::string> &words)
{
	std::string out;
	for (const std::string &w : words) {
		if (!out.empty())
			out += '|';
		out += w;
	}
	return out;
}

int main()
{
	std::set<std::string> commands;
	for (auto *f = giac::builtin_lexer_functions_begin(); f != giac::builtin_lexer_functions_end(); ++f)
		if (plain_identifier(f->first) && !KEYWORDS.count(f->first) && !CONSTANTS.count(f->first))
			commands.insert(f->first);

	std::printf(R"(%%YAML 1.2
---
# Giac / Xcas highlighting. Generated by tools/gen-syntax.cc from libgiac %s
# (%zu built-in commands); do not edit by hand.
name: Giac
file_extensions: [giac, xws]
scope: source.giac

contexts:
  main:
    - match: '//'
      scope: punctuation.definition.comment.giac
      push: line_comment
    - match: '/\*'
      scope: punctuation.definition.comment.begin.giac
      push: block_comment
    - match: '"'
      scope: punctuation.definition.string.begin.giac
      push: string
    - match: '\b0[xX][0-9a-fA-F]+\b'
      scope: constant.numeric.hex.giac
    - match: '(?<![A-Za-z_])(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?'
      scope: constant.numeric.giac
    - match: '\b(%s)\b'
      scope: keyword.control.giac
    - match: '\b(%s)\b'
      scope: constant.language.giac
    - match: '\b(%s)\b'
      scope: support.function.builtin.giac
    - match: '\b[A-Za-z_][A-Za-z0-9_]*(?=\s*\()'
      scope: variable.function.giac
    - match: ':=|=>|->|==|!=|<=|>=|&&|\|\||\.\.|[-+*/^=<>!%%@$]'
      scope: keyword.operator.giac
    - match: "'"
      scope: keyword.operator.derivative.giac
    - match: '[;:,]'
      scope: punctuation.separator.giac

  line_comment:
    - meta_scope: comment.line.double-slash.giac
    - match: '$'
      pop: true

  block_comment:
    - meta_scope: comment.block.giac
    - match: '\*/'
      scope: punctuation.definition.comment.end.giac
      pop: true

  string:
    - meta_scope: string.quoted.double.giac
    - match: '\\.'
      scope: constant.character.escape.giac
    - match: '"'
      scope: punctuation.definition.string.end.giac
      pop: true
)",
	            VERSION, commands.size(), alternation(KEYWORDS).c_str(), alternation(CONSTANTS).c_str(),
	            alternation(commands).c_str());
	return 0;
}
